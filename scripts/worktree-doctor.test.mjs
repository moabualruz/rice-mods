import assert from 'node:assert/strict';
import { spawnSync, execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, symlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';

const root = mkdtempSync(join(tmpdir(), 'mods-readiness-'));
const bin = join(root, 'bin');
const repo = join(root, 'repo');
mkdirSync(bin);
mkdirSync(repo);
mkdirSync(join(repo, 'scripts'));
mkdirSync(join(repo, 'release-packages', 'scripts'), { recursive: true });
const doctor = join(repo, 'scripts', 'worktree-doctor.sh');
writeFileSync(doctor, readFileSync(new URL('./worktree-doctor.sh', import.meta.url)));
for (const path of ['release-packages/scripts/plugin.sh', 'release-packages/scripts/vendor-lock.sh', 'release-packages.lock', 'vendir.lock.yml']) writeFileSync(join(repo, path), 'fixture\n');
const git = execFileSync('which', ['git'], { encoding: 'utf8' }).trim();
symlinkSync(git, join(bin, 'git'));
for (const name of ['jq', 'gh', 'tar', 'claude']) writeFileSync(join(bin, name), '#!/bin/sh\nexit 0\n', { mode: 0o755 });
const order = join(root, 'order');
writeFileSync(join(bin, 'just'), '#!/bin/sh\nprintf "%s\\n" readiness >> "$FIXTURE_ORDER"\n/bin/bash scripts/worktree-doctor.sh\n', { mode: 0o755 });
writeFileSync(join(bin, 'git-canonical-gate'), '#!/bin/sh\nprintf "%s\\n" canonical >> "$FIXTURE_ORDER"\nexit "${FIXTURE_GATE_EXIT:-0}"\n', { mode: 0o755 });
const env = { ...process.env, PATH: bin + ':' + dirname(process.execPath), FIXTURE_ORDER: order, GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_SYSTEM: '/dev/null' };
for (const name of Object.keys(env)) if (/^GIT_(DIR|WORK_TREE|INDEX_FILE|COMMON_DIR|OBJECT_DIRECTORY|ALTERNATE_OBJECT_DIRECTORIES)$/.test(name)) delete env[name];
const run = (command, args, options = {}) => spawnSync(command, args, { cwd: repo, encoding: 'utf8', env, ...options });
assert.equal(run('/bin/bash', [doctor]).status, 0);
const missing = join(root, 'missing-bin');
mkdirSync(missing);
const absent = run('/bin/bash', [doctor], { env: { ...env, PATH: missing } });
assert.notEqual(absent.status, 0);
assert.match(absent.stderr, /missing node/);
assert.match(absent.stderr, /Fix: mise install node@24.18.0/);
const gitRun = args => { const result = run(git, args); assert.equal(result.status, 0, result.stderr); return result.stdout.trim(); };
gitRun(['init', '-q', '--initial-branch=main']);
gitRun(['add', '.']);
gitRun(['-c', 'core.hooksPath=/dev/null', '-c', 'commit.gpgsign=false', '-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid', 'commit', '-qm', 'Readiness fixture']);
const head = gitRun(['rev-parse', 'HEAD']);
const hook = join(root, 'pre-push');
writeFileSync(hook, readFileSync(new URL('../.githooks/pre-push', import.meta.url)));
const input = `refs/heads/main ${head} refs/heads/main ${'0'.repeat(40)}\n`;
const missingProducer = run('/bin/bash', [hook], { input });
assert.notEqual(missingProducer.status, 0);
assert.match(missingProducer.stderr, /configure the owning canonical producer/);
gitRun(['config', '--local', 'rice.canonicalGateRoot', join(root, 'fixture-producer')]);
assert.equal(run('/bin/bash', [hook], { input }).status, 0);
assert.equal(readFileSync(order, 'utf8'), 'readiness\ncanonical\n');
assert.equal(run('/bin/bash', [hook], { input, env: { ...env, FIXTURE_GATE_EXIT: '37' } }).status, 37);
const before = readFileSync(order, 'utf8');
assert.notEqual(run('/bin/bash', [hook], { input: input.replace(head, 'b'.repeat(40)) }).status, 0);
assert.equal(readFileSync(order, 'utf8'), before);
const deletion = run('/bin/bash', [hook], { input: `refs/heads/main ${'0'.repeat(40)} refs/heads/main ${head}\n` });
assert.notEqual(deletion.status, 0);
assert.match(deletion.stderr, /branch deletion/);
assert.equal(readFileSync(order, 'utf8'), before);
const wrongNodeBin = join(root, 'wrong-node-bin');
mkdirSync(wrongNodeBin);
for (const name of ['git', 'just', 'jq', 'gh', 'tar', 'claude', 'git-canonical-gate']) symlinkSync(join(bin, name), join(wrongNodeBin, name));
writeFileSync(join(wrongNodeBin, 'node'), '#!/bin/sh\nprintf "%s\\n" v24.18.0\n', { mode: 0o755 });
const unready = run('/bin/bash', [hook], { input, env: { ...env, PATH: wrongNodeBin } });
assert.notEqual(unready.status, 0);
assert.match(unready.stderr, /mise 24.18.0 installation/);
assert.equal(readFileSync(order, 'utf8'), before + 'readiness\n');
const emptyCheckout = join(root, 'empty-checkout');
mkdirSync(join(emptyCheckout, 'scripts'), { recursive: true });
const emptyDoctor = join(emptyCheckout, 'scripts', 'worktree-doctor.sh');
writeFileSync(emptyDoctor, readFileSync(doctor));
const unmaterialized = run('/bin/bash', [emptyDoctor]);
assert.notEqual(unmaterialized.status, 0);
assert.match(unmaterialized.stderr, /missing release-packages\/scripts\/plugin.sh/);
assert.match(unmaterialized.stderr, /Fix: vendir sync --locked/);
